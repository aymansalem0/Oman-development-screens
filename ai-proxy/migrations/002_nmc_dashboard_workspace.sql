  CONSTRAINT PK_NMC_DASHBOARD_REVISION PRIMARY KEY (DASHBOARD_ID,VERSION_NO),
  CONSTRAINT FK_NMC_DASHBOARD_REVISION FOREIGN KEY (DASHBOARD_ID)
    REFERENCES NMC_DASHBOARD(DASHBOARD_ID)
