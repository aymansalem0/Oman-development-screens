                   CONSTRAINT CK_NMC_DASHBOARD_STATUS CHECK (STATUS IN ('DRAFT','PUBLISHED','ARCHIVED')),
  VERSION_NO       NUMBER(10,0) DEFAULT 1 NOT NULL
