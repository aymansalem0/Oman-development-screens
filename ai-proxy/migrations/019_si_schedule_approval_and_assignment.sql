-- MOEI Smart Inspection V2: Approved schedule and engineer reservation ledger.
-- Oracle 23c / NMC_AI / FREEPDB1. Additive only. Apply after 009,010,013,018
-- and only AFTER a verified restorable backup and inspection of existing schema.
-- No DROP/TRUNCATE/MERGE of existing cases or approval records.
SET DEFINE OFF
SET SERVEROUTPUT ON
WHENEVER SQLERROR EXIT SQL.SQLCODE
DECLARE
 n NUMBER;
 PROCEDURE ensure_table(p_name VARCHAR2,p_ddl VARCHAR2) IS
 BEGIN
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME=p_name;
  IF n=0 THEN EXECUTE IMMEDIATE p_ddl; DBMS_OUTPUT.PUT_LINE('CREATED '||p_name);
  ELSE DBMS_OUTPUT.PUT_LINE('PRESENT '||p_name); END IF;
 END;
 PROCEDURE ensure_index(p_name VARCHAR2,p_ddl VARCHAR2) IS
 BEGIN
  SELECT COUNT(*) INTO n FROM USER_INDEXES WHERE INDEX_NAME=p_name;
  IF n=0 THEN EXECUTE IMMEDIATE p_ddl; DBMS_OUTPUT.PUT_LINE('CREATED '||p_name); END IF;
 END;
BEGIN
 SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME IN
  ('SI_PLAN_ROLLING','SI_PLAN_ROLLING_VESSEL','SI_INSPECTION_CASE',
   'SI_PREPARATION_DOSSIER','SI_INSPECTION_LIFECYCLE');
 IF n<>5 THEN
  RAISE_APPLICATION_ERROR(-20019,'Prerequisites 009, 010, 013 and 018 must exist');
 END IF;
 ensure_table('SI_V2_SCHEDULE_MUTEX',q'[CREATE TABLE SI_V2_SCHEDULE_MUTEX (
  LOCK_ID NUMBER(1) PRIMARY KEY CHECK (LOCK_ID=1)
 )]');
 ensure_table('SI_V2_SCHEDULE_APPROVAL',q'[CREATE TABLE SI_V2_SCHEDULE_APPROVAL (
  SCHEDULE_ID VARCHAR2(36) PRIMARY KEY,
  PLAN_ID VARCHAR2(36) NOT NULL UNIQUE,
  PLAN_REVISION NUMBER(9) NOT NULL,
  PROPOSAL_HASH VARCHAR2(64) NOT NULL,
  ERP_SNAPSHOT_ID VARCHAR2(160) NOT NULL,
  STATUS VARCHAR2(50) NOT NULL
    CHECK(STATUS IN ('APPROVED_AWAITING_CASES','WAITING_NMC_CONFIRMATION',
      'DISPATCH_IN_PROGRESS','DISPATCH_PARTIAL','DOSSIERS_PREPARED_SCOPE_APPROVAL_PENDING')),
  DOC_JSON CLOB NOT NULL CHECK(DOC_JSON IS JSON),
  APPROVED_BY VARCHAR2(160) NOT NULL,
  APPROVED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT FK_SI_V2_SCHEDULE_PLAN FOREIGN KEY(PLAN_ID)
    REFERENCES SI_PLAN_ROLLING(PLAN_ID)
 )]');
 ensure_table('SI_V2_SCHEDULE_ASSIGNMENT',q'[CREATE TABLE SI_V2_SCHEDULE_ASSIGNMENT (
  SCHEDULE_ID VARCHAR2(36) NOT NULL,
  IMO VARCHAR2(7) NOT NULL,
  INSPECTOR_ID VARCHAR2(120) NOT NULL,
  START_UTC VARCHAR2(35) NOT NULL,
  END_UTC VARCHAR2(35) NOT NULL,
  PORT_ID VARCHAR2(100) NOT NULL,
  CASE_ID VARCHAR2(36),
  DOC_JSON CLOB NOT NULL CHECK(DOC_JSON IS JSON),
  CONSTRAINT PK_SI_V2_SCHEDULE_ASSIGN PRIMARY KEY(SCHEDULE_ID,IMO),
  CONSTRAINT FK_SI_V2_SCHEDULE_ASSIGN FOREIGN KEY(SCHEDULE_ID)
    REFERENCES SI_V2_SCHEDULE_APPROVAL(SCHEDULE_ID),
  CONSTRAINT FK_SI_V2_SCHEDULE_CASE FOREIGN KEY(CASE_ID)
    REFERENCES SI_INSPECTION_CASE(CASE_ID)
 )]');
 ensure_table('SI_V2_SCHEDULE_AUDIT',q'[CREATE TABLE SI_V2_SCHEDULE_AUDIT (
  AUDIT_ID VARCHAR2(36) PRIMARY KEY,
  SCHEDULE_ID VARCHAR2(36) NOT NULL,
  EVENT_CODE VARCHAR2(70) NOT NULL,
  ACTOR VARCHAR2(160) NOT NULL,
  DETAILS_JSON CLOB CHECK(DETAILS_JSON IS JSON),
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT FK_SI_V2_SCHEDULE_AUDIT FOREIGN KEY(SCHEDULE_ID)
   REFERENCES SI_V2_SCHEDULE_APPROVAL(SCHEDULE_ID)
 )]');
 ensure_index('IDX_SI_V2_SCHED_INSPECTOR',q'[CREATE INDEX IDX_SI_V2_SCHED_INSPECTOR
  ON SI_V2_SCHEDULE_ASSIGNMENT(INSPECTOR_ID,START_UTC,END_UTC)]');
 ensure_index('IDX_SI_V2_SCHED_STATUS',q'[CREATE INDEX IDX_SI_V2_SCHED_STATUS
  ON SI_V2_SCHEDULE_APPROVAL(STATUS,UPDATED_AT)]');
 ensure_index('IDX_SI_V2_SCHED_AUDIT',q'[CREATE INDEX IDX_SI_V2_SCHED_AUDIT
  ON SI_V2_SCHEDULE_AUDIT(SCHEDULE_ID,CREATED_AT)]');
 -- Dynamic SQL is required here: PL/SQL resolves static table references
 -- at compilation, BEFORE the CREATE TABLE statements above execute.
 -- A fresh schema would otherwise fail with ORA-00942 / ORA-06550.
 EXECUTE IMMEDIATE
  'SELECT COUNT(*) FROM SI_V2_SCHEDULE_MUTEX WHERE LOCK_ID = :lock_id'
  INTO n USING 1;
 IF n=0 THEN
  EXECUTE IMMEDIATE
   'INSERT INTO SI_V2_SCHEDULE_MUTEX (LOCK_ID) VALUES (:lock_id)'
   USING 1;
  DBMS_OUTPUT.PUT_LINE('SEEDED SI_V2_SCHEDULE_MUTEX LOCK_ID=1');
 ELSE
  DBMS_OUTPUT.PUT_LINE('PRESENT SI_V2_SCHEDULE_MUTEX LOCK_ID=1');
 END IF;
 COMMIT;
END;
/
PROMPT SI V2 Schedule Approval schema ready. Confirm indexes and existing data before enabling.
