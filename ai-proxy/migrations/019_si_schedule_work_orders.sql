DECLARE
 n NUMBER;
 PROCEDURE ensure_table(p_name VARCHAR2,p_sql VARCHAR2) IS
 BEGIN
  SELECT COUNT(*) INTO n FROM USER_TABLES WHERE TABLE_NAME=p_name;
  IF n=0 THEN EXECUTE IMMEDIATE p_sql; DBMS_OUTPUT.PUT_LINE('CREATED '||p_name);
  ELSE DBMS_OUTPUT.PUT_LINE('EXISTS '||p_name); END IF;
 END;
 PROCEDURE ensure_index(p_name VARCHAR2,p_sql VARCHAR2) IS
 BEGIN
  SELECT COUNT(*) INTO n FROM USER_INDEXES WHERE INDEX_NAME=p_name;
  IF n=0 THEN EXECUTE IMMEDIATE p_sql; DBMS_OUTPUT.PUT_LINE('CREATED '||p_name); END IF;
 END;
BEGIN
 SELECT COUNT(*) INTO n FROM USER_TABLES
 WHERE TABLE_NAME IN ('SI_PLAN_ROLLING','SI_INSPECTION_CASE',
  'SI_PREPARATION_DOSSIER','SI_INSPECTION_LIFECYCLE','SI_CHK_CASE_RUN');
 IF n<>5 THEN RAISE_APPLICATION_ERROR(-20019,
  'Required SI migrations 009, 010, 013, 017 and 018 are missing'); END IF;
 ensure_table('SI_SCHED_MUTEX',q'[CREATE TABLE SI_SCHED_MUTEX(
  LOCK_ID NUMBER(1) PRIMARY KEY CHECK(LOCK_ID=1))]');
 ensure_table('SI_SCHED_APPROVAL',q'[CREATE TABLE SI_SCHED_APPROVAL(
  SCHEDULE_ID VARCHAR2(36) PRIMARY KEY,
  PLAN_ID VARCHAR2(36) NOT NULL UNIQUE,
  PLAN_REVISION NUMBER(9) NOT NULL,
  PROPOSAL_HASH VARCHAR2(64) NOT NULL,
  OPTION_ID VARCHAR2(80) NOT NULL,
  ERP_SNAPSHOT_ID VARCHAR2(160) NOT NULL,
  MODE_CODE VARCHAR2(32) NOT NULL CHECK(MODE_CODE IN ('POC_MOCK','ERP_EXCEL_POC')),
  DOC_JSON CLOB NOT NULL CHECK(DOC_JSON IS JSON),
