  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT FK_SI_SCHED_AUDIT_SCHEDULE FOREIGN KEY(SCHEDULE_ID)
   REFERENCES SI_SCHED_APPROVAL(SCHEDULE_ID))]');
 ensure_index('IDX_SI_SCHED_WORK_INSPECTOR',
  q'[CREATE INDEX IDX_SI_SCHED_WORK_INSPECTOR
   ON SI_SCHED_WORK_ORDER(INSPECTOR_ID,START_UTC,END_UTC)]');
