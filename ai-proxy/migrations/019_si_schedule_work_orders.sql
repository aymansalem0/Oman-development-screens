  'SELECT COUNT(*) FROM SI_SCHED_MUTEX WHERE LOCK_ID=:lock_id'
  INTO n USING 1;
 IF n=0 THEN
  EXECUTE IMMEDIATE
   'INSERT INTO SI_SCHED_MUTEX(LOCK_ID) VALUES(:lock_id)' USING 1;
 END IF;
 COMMIT;
END;
