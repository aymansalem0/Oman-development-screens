  CONSTRAINT FK_SI_SCHED_WORK_CASE FOREIGN KEY(CASE_ID)
   REFERENCES SI_INSPECTION_CASE(CASE_ID))]');
 ensure_table('SI_SCHED_ORDER_AUDIT',q'[CREATE TABLE SI_SCHED_ORDER_AUDIT(
