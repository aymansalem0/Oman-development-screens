   REFERENCES SI_PLAN_ROLLING(PLAN_ID))]');
 ensure_table('SI_SCHED_WORK_ORDER',q'[CREATE TABLE SI_SCHED_WORK_ORDER(
  ORDER_ID VARCHAR2(36) PRIMARY KEY,
  SCHEDULE_ID VARCHAR2(36) NOT NULL,
  IMO VARCHAR2(7) NOT NULL,
  INSPECTOR_ID VARCHAR2(120) NOT NULL,
  START_UTC VARCHAR2(35) NOT NULL,
  END_UTC VARCHAR2(35) NOT NULL,
  PORT_ID VARCHAR2(100) NOT NULL,
  CASE_ID VARCHAR2(36),
  STATUS_CODE VARCHAR2(45) NOT NULL,
  VERSION_NO NUMBER(9) DEFAULT 1 NOT NULL,
  DOC_JSON CLOB NOT NULL CHECK(DOC_JSON IS JSON),
  CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  UPDATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT UK_SI_SCHED_WORK_ORDER UNIQUE(SCHEDULE_ID,IMO),
