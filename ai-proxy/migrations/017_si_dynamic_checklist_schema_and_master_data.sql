DECLARE
  PROCEDURE ensure_md_group(p_code VARCHAR2,p_en VARCHAR2,p_ar VARCHAR2) IS
  BEGIN
    MERGE INTO SI_CHK_MD_GROUP d
    USING (SELECT p_code CODE,p_en EN,p_ar AR FROM DUAL) s
    ON(d.GROUP_CODE=s.CODE)
    WHEN NOT MATCHED THEN INSERT(GROUP_CODE,NAME_EN,NAME_AR)
      VALUES(s.CODE,s.EN,s.AR);
  END;
